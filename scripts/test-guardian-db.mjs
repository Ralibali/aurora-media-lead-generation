import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';
const db = new PGlite();
await db.exec('create role anon; create role authenticated; create role service_role bypassrls;');
await db.exec(await readFile('supabase/migrations/20260928065604_website_guardian.sql','utf8'));
await db.exec(await readFile('supabase/migrations/20261001084700_sitewatch_commercial_layer.sql','utf8'));
// Storage's managed schema exists in Supabase. Model only its bucket metadata locally.
await db.exec(`create schema storage; create table storage.buckets(id text primary key,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]);
  create table storage.objects(id uuid default gen_random_uuid(),bucket_id text); alter table storage.objects enable row level security;
  grant usage on schema storage to anon,authenticated; grant all on storage.objects to anon,authenticated;
  create policy existing_broad_policy on storage.objects for all to anon,authenticated using(true) with check(true);
  insert into storage.objects(bucket_id) values('aurora-watch-evidence'),('existing-public-media');`);
await db.exec(await readFile('supabase/migrations/20261005151557_aurora_watch_browser_flows.sql','utf8'));
for (const role of ['anon','authenticated']) {
  await db.exec(`set role ${role}`);
  await assert.rejects(()=>db.query('select * from guardian_sites'),/permission denied/);
  await assert.rejects(()=>db.query('select * from guardian_checks'),/permission denied/);
  await assert.rejects(()=>db.query('select * from guardian_flows'),/permission denied/);
  await assert.rejects(()=>db.query('select * from guardian_flow_runs'),/permission denied/);
  await assert.rejects(()=>db.query("select * from guardian_claim_flows(1,array['https://example.test'])"),/permission denied/);
  await assert.rejects(()=>db.query("select guardian_complete_flow(gen_random_uuid(),gen_random_uuid(),'{}')"),/permission denied/);
  await assert.rejects(()=>db.query("select guardian_edit_flow(gen_random_uuid(),'{}')"),/permission denied/);
  const visibleObjects=(await db.query('select bucket_id from storage.objects')).rows;
  assert.deepEqual(visibleObjects,[{bucket_id:'existing-public-media'}],'Existing broad media policies must not expose private evidence');
  await assert.rejects(()=>db.query("insert into storage.objects(bucket_id) values('aurora-watch-evidence')"),/row-level security/);
  await db.exec('reset role');
}
await db.exec('set role service_role');
const created=(await db.query("insert into guardian_sites(name,url) values('Test','https://example.test') returning id,check_interval_minutes,last_notified_state")).rows[0];
assert.equal(created.check_interval_minutes,60);
assert.equal(created.last_notified_state,'none');
const site=created.id;
await assert.rejects(()=>db.query("update guardian_sites set check_interval_minutes=30 where id=$1",[site]),/guardian_sites_interval_check/);
await db.query("update guardian_sites set check_interval_minutes=15,notify_email='drift@example.test' where id=$1",[site]);
await db.query("insert into guardian_checks(site_id,slot,status) values($1,'2026-09-28T08:00:00Z','running')",[site]);
await assert.rejects(()=>db.query("insert into guardian_checks(site_id,slot,status) values($1,'2026-09-28T08:00:00Z','running')",[site]),/unique/);
await db.query("update guardian_checks set status='healthy' where site_id=$1",[site]);
assert.equal((await db.query('select status from guardian_checks')).rows[0].status,'healthy');
const steps=[{type:'navigate',url:'https://example.test'},{type:'assert_visible',selector:'main'}];
const flow=(await db.query('insert into guardian_flows(site_id,name,steps) values($1,$2,$3) returning id',[site,'Main navigation',JSON.stringify(steps)])).rows[0].id;
const claim=async()=> (await db.query("select * from guardian_claim_flows(1,array['https://example.test'])")).rows;
const complete=async(run,result)=> (await db.query('select guardian_complete_flow($1,$2,$3) as result',[run.run_id,run.lease_token,JSON.stringify(result)])).rows[0].result;
const queue=async()=>db.query('select guardian_edit_flow($1,$2)',[flow,'{"queue":true}']);
const pass={status:'passed',attempts:1,duration_ms:42,steps:[]};
const fail={status:'failed',attempts:2,duration_ms:50,error:'Expected form missing',steps:[]};
assert.equal((await db.query("select * from guardian_claim_flows(5,array['https://unapproved.test'])")).rows.length,0);
const first=(await claim())[0];
assert.equal(first.flow_id,flow); assert.deepEqual(first.steps,steps);
assert.equal((await claim()).length,0,'A live lease cannot be claimed twice');
await assert.rejects(queue,/GUARDIAN_FLOW_BUSY/);
await assert.rejects(()=>db.query('select guardian_complete_flow($1,gen_random_uuid(),$2)',[first.run_id,JSON.stringify(pass)]),/GUARDIAN_LEASE_INVALID/);
assert.equal((await complete(first,fail)).incident_state,'first_failure');
assert.equal((await complete(first,pass)).idempotent,true,'Retry must not overwrite a completed failure');
assert.equal((await db.query('select status from guardian_flow_runs where id=$1',[first.run_id])).rows[0].status,'failed');
await queue(); const second=(await claim())[0];
assert.equal((await complete(second,fail)).incident_state,'confirmed_failure');
await queue(); const third=(await claim())[0];
assert.equal((await complete(third,pass)).incident_state,'recovered');
await queue(); const stale=(await claim())[0];
await db.query("update guardian_flow_runs set lease_expires_at=now()-interval '1 second' where id=$1",[stale.run_id]);
await assert.rejects(()=>complete(stale,pass),/GUARDIAN_LEASE_EXPIRED/);
assert.equal((await claim()).length,0,'A daily flow is not due yet after lease expiry');
assert.equal((await db.query('select status from guardian_flow_runs where id=$1',[stale.run_id])).rows[0].status,'inconclusive','Expired daily leases must still be reaped');
await queue(); const replacement=(await claim())[0];
assert.notEqual(replacement.run_id,stale.run_id);
assert.equal((await db.query('select status from guardian_flow_runs where id=$1',[stale.run_id])).rows[0].status,'inconclusive');
await assert.rejects(()=>complete(stale,pass),/GUARDIAN_LEASE_EXPIRED/);
await complete(replacement,pass);
await queue(); const infrastructure=(await claim())[0];
const inconclusive=await complete(infrastructure,{status:'inconclusive',attempts:0,duration_ms:12,steps:[],error:'Browser could not start'});
assert.equal(inconclusive.incident_state,'unknown');
assert.equal((await complete(infrastructure,pass)).idempotent,true);
assert.equal((await db.query('select status from guardian_flow_runs where id=$1',[infrastructure.run_id])).rows[0].status,'inconclusive');
await db.query('select guardian_edit_flow($1,$2)',[flow,'{"active":false}']);
await assert.rejects(queue,/GUARDIAN_FLOW_PAUSED/);
assert.equal((await claim()).length,0);
await db.exec('reset role');
assert.equal((await db.query("select public from storage.buckets where id='aurora-watch-evidence'")).rows[0].public,false);
// Verify RLS itself still prevents leakage if a future migration accidentally grants SELECT.
await db.exec('grant select on guardian_flows,guardian_flow_runs to anon,authenticated;');
for(const role of ['anon','authenticated']) {
  await db.exec(`set role ${role}`);
  assert.equal((await db.query('select * from guardian_flows')).rows.length,0);
  assert.equal((await db.query('select * from guardian_flow_runs')).rows.length,0);
  await db.exec('reset role');
}
const functions=(await db.query("select prosecdef from pg_proc where proname in ('guardian_claim_flows','guardian_complete_flow','guardian_edit_flow')")).rows;
assert.equal(functions.length,3); assert.ok(functions.every(f=>f.prosecdef===false));
await db.close(); console.log('Guardian DB: RLS, private bucket, service-only invoker RPCs, leases, idempotency, stale results and incident transitions verified.');
